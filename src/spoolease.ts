// ABOUTME: SpoolEase encrypted API client for spool and custom filament updates.
// ABOUTME: Uses documented endpoint behavior from SpoolEase docs and source references.

import { DEFAULT_ITERATIONS, DEFAULT_SALT, decryptText, deriveKey, encryptText } from "./encryption.js";
import type { FilamentProfile } from "./models.js";

const REQUEST_TIMEOUT_MS = 20_000;

export interface SpoolEaseConnection {
  host: string;
  securityKey: string;
  port: number;
  https: boolean;
  salt?: string;
  iterations?: number;
}

export interface SpoolEaseResponse {
  status: number;
  /** Decrypted body on success; raw body on errors or undecryptable replies. */
  body: string;
}

export class SpoolEaseClient {
  readonly baseUrl: string;
  private readonly key: Buffer;

  constructor(conn: SpoolEaseConnection) {
    this.baseUrl = `${conn.https ? "https" : "http"}://${conn.host}:${conn.port}`;
    this.key = deriveKey(conn.securityKey, conn.salt ?? DEFAULT_SALT, conn.iterations ?? DEFAULT_ITERATIONS);
  }

  private async postEncrypted(path: string, payload: unknown): Promise<SpoolEaseResponse> {
    const resp = await fetch(`${this.baseUrl}${path}`, {
      method: "POST",
      headers: { "Content-Type": "application/text" },
      body: encryptText(this.key, JSON.stringify(payload)),
      signal: AbortSignal.timeout(REQUEST_TIMEOUT_MS),
    });
    const body = await resp.text();
    if (resp.status >= 400) return { status: resp.status, body };
    try {
      return { status: resp.status, body: decryptText(this.key, body) };
    } catch {
      return { status: resp.status, body };
    }
  }

  async testKey(): Promise<boolean> {
    const { status } = await this.postEncrypted("/api/test-key", { test: "Hello" });
    return status === 200;
  }

  /** Create a SpoolEase spool record; an empty id asks SpoolEase to create a new one. */
  addOrEditSpool(profile: FilamentProfile): Promise<SpoolEaseResponse> {
    return this.postEncrypted("/api/spools/add-edit", spoolPayload(profile));
  }

  setCustomFilamentsCsv(csvText: string): Promise<SpoolEaseResponse> {
    return this.postEncrypted("/api/filaments-config", { custom_filaments: csvText });
  }
}

export function spoolPayload(profile: FilamentProfile): Record<string, unknown> {
  return {
    tag_id: "",
    id: "",
    rgba: profile.colorRgba,
    color_name: profile.colorName,
    material: profile.material,
    subtype: "",
    brand: profile.brand,
    core_weight: 200,
    label_weight: 1000,
    note: `Generated by bambu-hando for ${profile.name}`,
    slicer_filament: profile.slicerFilamentCode,
    full_unused: "y",
    k_info: null,
  };
}

/** The profile's slicer code, or a generated P + 6 hex digit code from its 1-based position. */
export function customFilamentCode(profile: FilamentProfile, position: number): string {
  return profile.slicerFilamentCode || `P${position.toString(16).toUpperCase().padStart(6, "0")}`;
}

/** Generate SpoolEase custom-filaments CSV lines: code,name,nozzle_temp_low,nozzle_temp_high,material */
export function buildCustomFilamentsCsv(profiles: FilamentProfile[]): string {
  return profiles
    .map((p, idx) => `${customFilamentCode(p, idx + 1)},${p.brand} ${p.name},${p.nozzleTempMin},${p.nozzleTempMax},${p.material}`)
    .join("\r\n");
}

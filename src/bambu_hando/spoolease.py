"""ABOUTME: SpoolEase encrypted API client for spool and custom filament updates.
ABOUTME: Uses documented endpoint behavior from SpoolEase docs and source references."""

from __future__ import annotations

from dataclasses import dataclass
import json

import requests

from .encryption import DEFAULT_ITERATIONS, DEFAULT_SALT, derive_key, encrypt_text, decrypt_text
from .models import FilamentProfile


@dataclass(frozen=True)
class SpoolEaseConnection:
    console_host: str
    security_key: str
    api_token: str = ""
    port: int = 80
    use_https: bool = False
    salt: str = DEFAULT_SALT
    iterations: int = DEFAULT_ITERATIONS

    @property
    def base_url(self) -> str:
        scheme = "https" if self.use_https else "http"
        return f"{scheme}://{self.console_host}:{self.port}"


class SpoolEaseClient:
    def __init__(self, conn: SpoolEaseConnection) -> None:
        self._conn = conn
        self._key = derive_key(conn.security_key, salt=conn.salt, iterations=conn.iterations)
        self._session = requests.Session()

    def _post_encrypted(self, path: str, payload: dict) -> tuple[int, str]:
        body = encrypt_text(self._key, json.dumps(payload))
        headers = {"Content-Type": "application/text"}
        resp = self._session.post(f"{self._conn.base_url}{path}", data=body, headers=headers, timeout=20)
        if resp.status_code >= 400:
            return resp.status_code, resp.text
        try:
            decoded = decrypt_text(self._key, resp.text)
            return resp.status_code, decoded
        except Exception:
            return resp.status_code, resp.text

    def test_key(self) -> bool:
        status, _ = self._post_encrypted("/api/test-key", {"test": "Hello"})
        return status == 200

    def add_or_edit_spool(self, profile: FilamentProfile) -> tuple[int, str]:
        """Create a SpoolEase spool record from normalized profile.

        This uses /api/spools/add-edit with an empty id to create a new record.
        """

        payload = {
            "tag_id": "",
            "id": "",
            "rgba": profile.color_rgba,
            "color_name": profile.color_name,
            "material": profile.material,
            "subtype": "",
            "brand": profile.brand,
            "core_weight": 200,
            "label_weight": 1000,
            "note": f"Generated by bambu-hando for {profile.name}",
            "slicer_filament": profile.slicer_filament_code,
            "full_unused": "y",
            "k_info": None,
        }
        return self._post_encrypted("/api/spools/add-edit", payload)

    def set_custom_filaments_csv(self, csv_text: str) -> tuple[int, str]:
        payload = {"custom_filaments": csv_text}
        return self._post_encrypted("/api/filaments-config", payload)


def build_custom_filaments_csv(profiles: list[FilamentProfile]) -> str:
    """Generate SpoolEase custom-filaments CSV lines.

    Format per docs/source examples:
    code,name,nozzle_temp_low,nozzle_temp_high,material
    """

    lines: list[str] = []
    for idx, p in enumerate(profiles, start=1):
        code = p.slicer_filament_code or f"P{idx:06X}"
        line = f"{code},{p.brand} {p.name},{p.nozzle_temp_min},{p.nozzle_temp_max},{p.material}"
        lines.append(line)
    return "\r\n".join(lines)

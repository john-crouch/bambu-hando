"""ABOUTME: BambuStudio custom filament preset writer for Linux and macOS.
ABOUTME: Writes JSON user presets with conservative, idempotent behavior."""

from __future__ import annotations

from dataclasses import asdict
from pathlib import Path
import json
import re

from .colors import rgba_to_hash_rgb
from .models import FilamentProfile
from .paths import bambu_filament_dir


_SAFE = re.compile(r"[^A-Za-z0-9._ @()-]+")


def _safe_name(name: str) -> str:
    return _SAFE.sub("_", name).strip() or "unnamed"


def _build_preset(profile: FilamentProfile, printer_preset: str) -> dict:
    # This shape follows known BambuStudio JSON-user-preset conventions.
    # Some fields are inferred; they are documented in docs/assumptions.md.
    preset_name = f"{profile.name} @ {printer_preset}"
    return {
        "type": "filament",
        "name": preset_name,
        "from": "User",
        "inherits": "",
        "filament_type": [profile.material],
        "filament_vendor": [profile.brand],
        "default_filament_colour": rgba_to_hash_rgb(profile.color_rgba),
        "filament_density": [str(profile.density)],
        "filament_diameter": [str(profile.diameter)],
        "nozzle_temperature": [str(profile.nozzle_temp_max)],
        "nozzle_temperature_initial_layer": [str(profile.nozzle_temp_max)],
        "temperature_vitrification": [str(profile.nozzle_temp_min)],
        "filament_settings_id": [profile.name],
        "notes": f"Generated by bambu-hando for {profile.brand} {profile.material} {profile.color_name}",
    }


def _preset_path(profile: FilamentProfile, preset_folder: str, printer_preset: str) -> Path:
    return bambu_filament_dir(preset_folder=preset_folder) / f"{_safe_name(profile.name)} @ {printer_preset}.json"


def write_filament_preset(
    profile: FilamentProfile,
    preset_folder: str = "default",
    printer_preset: str = "Bambu Lab X1C 0.4 nozzle",
    dry_run: bool = False,
) -> Path:
    target = _preset_path(profile, preset_folder=preset_folder, printer_preset=printer_preset)
    target_dir = target.parent

    payload = _build_preset(profile, printer_preset=printer_preset)

    if dry_run:
        return target

    target_dir.mkdir(parents=True, exist_ok=True)
    temp = target.with_suffix(".json.tmp")
    temp.write_text(json.dumps(payload, indent=2, ensure_ascii=True), encoding="utf-8")
    temp.replace(target)
    return target


def write_many(
    profiles: list[FilamentProfile],
    preset_folder: str,
    printer_preset: str,
    dry_run: bool = False,
) -> list[tuple[Path, str]]:
    """Write each preset, returning (target path, error message or "") per profile."""

    outcomes: list[tuple[Path, str]] = []
    for p in profiles:
        target = _preset_path(p, preset_folder=preset_folder, printer_preset=printer_preset)
        try:
            write_filament_preset(
                profile=p,
                preset_folder=preset_folder,
                printer_preset=printer_preset,
                dry_run=dry_run,
            )
        except OSError as exc:
            outcomes.append((target, str(exc)))
            continue
        outcomes.append((target, ""))
    return outcomes

// ABOUTME: BambuStudio custom filament preset writer for Linux and macOS.
// ABOUTME: Writes JSON user presets atomically; dry-run never touches disk.

import { mkdir, rename, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";

import { rgbaToHashRgb } from "./colors.js";
import type { FilamentProfile } from "./models.js";
import { bambuFilamentDir } from "./paths.js";

const SAFE = /[^A-Za-z0-9._ @()-]+/g;

function safeName(name: string): string {
  return name.replace(SAFE, "_").trim() || "unnamed";
}

// BambuStudio presets store floats the way Python's str() renders them, so whole numbers keep a ".0".
function floatText(value: number): string {
  return Number.isInteger(value) ? value.toFixed(1) : String(value);
}

// Escape non-ASCII as \uXXXX so preset files stay byte-identical to the original Python writer.
function asciiJson(value: unknown): string {
  return JSON.stringify(value, null, 2).replace(/[\u0080-￿]/g, (c) => `\\u${c.charCodeAt(0).toString(16).padStart(4, "0")}`);
}

function buildPreset(profile: FilamentProfile, printerPreset: string): Record<string, unknown> {
  // This shape follows known BambuStudio JSON-user-preset conventions.
  // Some fields are inferred; they are documented in docs/assumptions.md.
  return {
    type: "filament",
    name: `${profile.name} @ ${printerPreset}`,
    from: "User",
    inherits: "",
    filament_type: [profile.material],
    filament_vendor: [profile.brand],
    default_filament_colour: rgbaToHashRgb(profile.colorRgba),
    filament_density: [floatText(profile.density)],
    filament_diameter: [floatText(profile.diameter)],
    nozzle_temperature: [String(profile.nozzleTempMax)],
    nozzle_temperature_initial_layer: [String(profile.nozzleTempMax)],
    temperature_vitrification: [String(profile.nozzleTempMin)],
    filament_settings_id: [profile.name],
    notes: `Generated by bambu-hando for ${profile.brand} ${profile.material} ${profile.colorName}`,
  };
}

export function presetJson(profile: FilamentProfile, printerPreset: string): string {
  return asciiJson(buildPreset(profile, printerPreset));
}

export function presetPath(profile: FilamentProfile, presetFolder: string, printerPreset: string): string {
  return join(bambuFilamentDir(presetFolder), `${safeName(profile.name)} @ ${printerPreset}.json`);
}

export async function writeFilamentPreset(
  profile: FilamentProfile,
  presetFolder = "default",
  printerPreset = "Bambu Lab X1C 0.4 nozzle",
  dryRun = false,
): Promise<string> {
  const target = presetPath(profile, presetFolder, printerPreset);
  const payload = presetJson(profile, printerPreset);

  if (dryRun) return target;

  await mkdir(dirname(target), { recursive: true });
  const temp = `${target}.tmp`;
  await writeFile(temp, payload, "utf-8");
  await rename(temp, target);
  return target;
}

export interface PresetOutcome {
  path: string;
  /** Empty when the write (or dry-run plan) succeeded. */
  error: string;
}

/** Write each preset, returning the target path and error message (or "") per profile. */
export async function writeMany(
  profiles: FilamentProfile[],
  presetFolder: string,
  printerPreset: string,
  dryRun = false,
): Promise<PresetOutcome[]> {
  const outcomes: PresetOutcome[] = [];
  for (const profile of profiles) {
    const path = presetPath(profile, presetFolder, printerPreset);
    try {
      await writeFilamentPreset(profile, presetFolder, printerPreset, dryRun);
      outcomes.push({ path, error: "" });
    } catch (err) {
      outcomes.push({ path, error: err instanceof Error ? err.message : String(err) });
    }
  }
  return outcomes;
}

// ABOUTME: More spools of a filament the SpoolEase console already has: copies of its newest spool record.
// ABOUTME: The preset and custom-filament row already exist, so a copy only adds spool records.

import { errorMessage } from "./errors.js";
import type { CustomFilament, SpoolEaseClient, SpoolEaseWrite, SpoolRecord } from "./spoolease.js";

export interface CopyableFilament {
  /** The slicer filament code every spool of it shares. */
  code: string;
  name: string;
  /** Spools of it on the console now. */
  count: number;
  /** Its newest spool: what copies are made from. */
  spool: SpoolRecord;
}

function spoolName(spool: SpoolRecord): string {
  return [spool.brand, spool.material, spool.colorName].filter(Boolean).join(" ") || spool.slicerFilament;
}

/**
 * Filaments with at least one spool, by name: the custom-filament name when the console has one, else
 * the spool's brand, material and color. Spools without a slicer filament code are left out, because
 * nothing would link a copy to a BambuStudio preset.
 */
export function copyableFilaments(spools: SpoolRecord[], names: ReadonlyMap<string, CustomFilament>): CopyableFilament[] {
  const byCode = new Map<string, CopyableFilament>();
  for (const spool of spools) {
    if (!spool.slicerFilament) continue;
    const found = byCode.get(spool.slicerFilament);
    if (!found) {
      byCode.set(spool.slicerFilament, { code: spool.slicerFilament, name: "", count: 1, spool });
      continue;
    }
    found.count += 1;
    if (Number(spool.id) > Number(found.spool.id)) found.spool = spool;
  }
  return [...byCode.values()]
    .map((filament) => ({ ...filament, name: names.get(filament.code)?.name || spoolName(filament.spool) }))
    .sort((a, b) => a.name.localeCompare(b.name, undefined, { sensitivity: "base" }));
}

/**
 * A new spool like `spool`: same filament, color and weights; no tag, no location, unused. The note is
 * bambu-hando's own rather than a copy, since notes describe one physical spool.
 */
export function spoolCopyPayload(spool: SpoolRecord, name: string): Record<string, unknown> {
  return {
    tag_id: "",
    id: "",
    // Inferred: a multi-color record's codes are joined with ";" (docs/assumptions.md); only the first is sent.
    rgba: spool.colorCodes[0] ?? "",
    color_name: spool.colorName,
    material: spool.material,
    subtype: spool.subtype,
    brand: spool.brand,
    core_weight: spool.coreWeight ?? 0,
    label_weight: spool.labelWeight ?? 0,
    note: `Generated by bambu-hando for ${name}`,
    slicer_filament: spool.slicerFilament,
    full_unused: "y",
    k_info: null,
    assigned_location: "",
    actual_location: "",
    spools_count: 1,
  };
}

/** Add `count` copies one at a time, calling onEach after each; a failed copy doesn't stop the others. */
export async function addSpoolCopies(
  client: SpoolEaseClient,
  filament: CopyableFilament,
  count: number,
  onEach: (index: number, result: SpoolEaseWrite) => void = () => {},
): Promise<SpoolEaseWrite[]> {
  const results: SpoolEaseWrite[] = [];
  for (let index = 0; index < count; index++) {
    let result: SpoolEaseWrite;
    try {
      result = await client.addSpoolCopy(spoolCopyPayload(filament.spool, filament.name));
    } catch (err) {
      result = { ok: false, error: errorMessage(err) };
    }
    results.push(result);
    onEach(index, result);
  }
  return results;
}

// ABOUTME: Tests BambuStudio custom filament presets: content cloned from a Generic system preset,
// ABOUTME: file naming and location under filament/base, and dry-run/error handling in writeMany.

import { mkdir, mkdtemp, readdir, readFile, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";

import { beforeAll, beforeEach, describe, expect, it, vi } from "vitest";

import { SystemProfiles } from "../src/bambuProfiles.js";
import { buildPreset, presetJson, presetPath, writeMany } from "../src/bambuStudio.js";
import type { FilamentProfile } from "../src/models.js";
import { bambuConfigDir, baseFilamentDir, installBambuStudio, X1C_04, X1C_06 } from "./bambuStudioSetup.js";
import { profileAt } from "./parity.js";

let system: SystemProfiles;

beforeAll(async () => {
  const home = await mkdtemp(join(tmpdir(), "bambu-hando-system-"));
  await installBambuStudio(home);
  system = await SystemProfiles.load(bambuConfigDir(home));
});

function preset(profile: FilamentProfile, printer = X1C_04): Record<string, unknown> {
  const template = system.template(profile.material, printer);
  if (!template) throw new Error(`no template for ${profile.material}`);
  return buildPreset(profile, printer, template, system.version);
}

describe("buildPreset", () => {
  it("clones the Generic preset and sets the filament's identity like BambuStudio's Create filament", () => {
    const petg = preset(profileAt(0));

    expect(petg).toMatchObject({
      name: `PETG Red @${X1C_04}`,
      from: "User",
      inherits: "",
      version: "2.8.0.9",
      filament_id: "PABC1234",
      filament_settings_id: [`PETG Red @${X1C_04}`],
      filament_vendor: ["Polymaker"],
      filament_type: ["PETG"],
      compatible_printers: [X1C_04],
      compatible_printers_condition: "",
      default_filament_colour: ["#FF2200"],
      filament_density: ["1.27"],
      filament_diameter: ["1.75"],
      nozzle_temperature_range_low: ["230"],
      nozzle_temperature_range_high: ["255"],
      nozzle_temperature: ["255"],
      nozzle_temperature_initial_layer: ["255"],
      temperature_vitrification: ["70"],
    });
    expect(petg.filament_notes).toBe("Generated by bambu-hando from BambuStudio's Generic PETG preset.");
  });

  it("keeps the template's tuned settings", () => {
    const template = system.resolve("Generic PETG");
    const petg = preset(profileAt(0));

    for (const key of ["filament_max_volumetric_speed", "filament_flow_ratio", "fan_max_speed", "hot_plate_temp", "filament_start_gcode"]) {
      expect(petg[key], key).toEqual(template[key]);
    }
  });

  it("drops system-only metadata", () => {
    const petg = preset(profileAt(0));
    for (const key of ["type", "setting_id", "instantiation", "description"]) expect(petg).not.toHaveProperty(key);
  });

  it("keeps the template's nozzle temperature when it is inside the filament's range, and clamps it otherwise", () => {
    expect(preset({ ...profileAt(0), nozzleTempMin: 230, nozzleTempMax: 240 }).nozzle_temperature).toEqual(["240"]);
    expect(preset({ ...profileAt(0), nozzleTempMin: 260, nozzleTempMax: 270 }).nozzle_temperature).toEqual(["260"]);
    expect(preset(profileAt(2)).nozzle_temperature).toEqual(["220"]);
  });

  it("uses the base material's template and type for variants like PLA+", () => {
    const plus = preset({ ...profileAt(2), material: "PLA+" });

    expect(plus.filament_type).toEqual(["PLA"]);
    expect(plus.filament_notes).toBe("Generated by bambu-hando from BambuStudio's Generic PLA preset.");
  });

  it("replaces slashes in the name like BambuStudio does", () => {
    expect(preset({ ...profileAt(0), name: "PETG Red/Blue" }).name).toBe(`PETG Red-Blue @${X1C_04}`);
  });
});

describe("presetJson", () => {
  it("writes sorted keys with 4-space indentation and raw UTF-8, like BambuStudio", () => {
    const json = presetJson({ name: "Café™", compatible_printers: [X1C_04], filament_id: "P1" });
    expect(json).toBe(`{\n    "compatible_printers": [\n        "${X1C_04}"\n    ],\n    "filament_id": "P1",\n    "name": "Café™"\n}\n`);
  });
});

describe("writeMany", () => {
  let home: string;

  beforeEach(async () => {
    home = await mkdtemp(join(tmpdir(), "bambu-hando-home-"));
    vi.stubEnv("HOME", home);
  });

  const target = (printers = [X1C_04]) => ({ presetFolder: "1234567890", printers, system });

  it("names files after the preset under filament/base of the preset folder", () => {
    expect(presetPath(profileAt(1), "1234567890", X1C_04)).toBe(join(baseFilamentDir(home, "1234567890"), `Café Crème PLA @${X1C_04}.json`));
  });

  it("writes one preset per printer, all sharing the filament ID", async () => {
    const outcomes = await writeMany([profileAt(0)], target([X1C_04, X1C_06]), false);

    const dir = baseFilamentDir(home, "1234567890");
    expect(outcomes).toEqual([{ paths: [join(dir, `PETG Red @${X1C_04}.json`), join(dir, `PETG Red @${X1C_06}.json`)], error: "" }]);
    expect((await readdir(dir)).sort()).toEqual([`PETG Red @${X1C_04}.json`, `PETG Red @${X1C_06}.json`]);
    const written = JSON.parse(await readFile(join(dir, `PETG Red @${X1C_06}.json`), "utf-8"));
    expect(written).toMatchObject({ filament_id: "PABC1234", compatible_printers: [X1C_06] });
  });

  it("dry-run plans the paths without touching disk", async () => {
    const outcomes = await writeMany([profileAt(0)], target(), true);

    expect(outcomes[0]).toEqual({ paths: [join(baseFilamentDir(home, "1234567890"), `PETG Red @${X1C_04}.json`)], error: "" });
    await expect(readdir(baseFilamentDir(home, "1234567890"))).rejects.toThrow("ENOENT");
  });

  it("fails a profile without a Generic template and still writes the others", async () => {
    const outcomes = await writeMany([{ ...profileAt(0), material: "PVB" }, profileAt(2)], target(), false);

    expect(outcomes[0]?.error).toBe(`no Generic PVB preset in BambuStudio for ${X1C_04}`);
    expect(outcomes[1]?.error).toBe("");
    expect(await readdir(baseFilamentDir(home, "1234567890"))).toEqual([`Mystery Spool @${X1C_04}.json`]);
  });

  it("reports filesystem errors per profile", async () => {
    const dir = baseFilamentDir(home, "1234567890");
    await mkdir(join(dir, ".."), { recursive: true });
    await writeFile(dir, "not a directory", "utf-8");

    const outcomes = await writeMany([profileAt(0)], target(), false);

    expect(outcomes[0]?.error).toContain("EEXIST");
  });
});
